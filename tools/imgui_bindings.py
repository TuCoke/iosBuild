#!/usr/bin/env python3
"""生成经过显式审核的 cimgui 控件绑定；未知结构/回调不猜测 ABI。"""
from pathlib import Path
import argparse
import shutil
import subprocess

# Go 名称、返回类型、参数、已核对的 cimgui 调用。
# 复杂的可变缓冲/指针接口在 widgets_ios.go 中单独实现。
SPECS = [
    ("Button", "bool", "label:string,width:float32,height:float32", "igButton(label,ImVec2_c{width,height})"),
    ("SmallButton", "bool", "label:string", "igSmallButton(label)"),
    ("Separator", "", "", "igSeparator()"),
    ("SameLine", "", "offset:float32,spacing:float32", "igSameLine(offset,spacing)"),
    ("Spacing", "", "", "igSpacing()"),
    ("Dummy", "", "width:float32,height:float32", "igDummy(ImVec2_c{width,height})"),
    ("Indent", "", "width:float32", "igIndent(width)"),
    ("Unindent", "", "width:float32", "igUnindent(width)"),
    ("BeginGroup", "", "", "igBeginGroup()"),
    ("EndGroup", "", "", "igEndGroup()"),
    ("PushID", "", "label:string", "igPushID_Str(label)"),
    ("PopID", "", "", "igPopID()"),
    ("Bullet", "", "", "igBullet()"),
    ("TreeNode", "bool", "label:string", "igTreeNode_Str(label)"),
    ("TreePop", "", "", "igTreePop()"),
    ("CollapsingHeader", "bool", "label:string,flags:int", "igCollapsingHeader_TreeNodeFlags(label,flags)"),
    ("Selectable", "bool", "label:string,selected:bool", "igSelectable_Bool(label,selected!=0,0,ImVec2_c{0,0})"),
    ("ProgressBar", "", "fraction:float32,width:float32,height:float32,label:string", "igProgressBar(fraction,ImVec2_c{width,height},label)"),
    ("BeginTooltip", "bool", "", "igBeginTooltip()"),
    ("EndTooltip", "", "", "igEndTooltip()"),
    ("Tooltip", "", "text:string", 'igSetTooltip("%s",text)'),
    ("OpenPopup", "", "label:string,flags:int", "igOpenPopup_Str(label,flags)"),
    ("BeginPopup", "bool", "label:string,flags:int", "igBeginPopup(label,flags)"),
    ("EndPopup", "", "", "igEndPopup()"),
    ("CloseCurrentPopup", "", "", "igCloseCurrentPopup()"),
    ("BeginTable", "bool", "label:string,columns:int,flags:int", "igBeginTable(label,columns,flags,ImVec2_c{0,0},0)"),
    ("EndTable", "", "", "igEndTable()"),
    ("TableNextRow", "", "flags:int,height:float32", "igTableNextRow(flags,height)"),
    ("TableNextColumn", "bool", "", "igTableNextColumn()"),
    ("TableSetColumnIndex", "bool", "index:int", "igTableSetColumnIndex(index)"),
    ("BeginDisabled", "", "disabled:bool", "igBeginDisabled(disabled!=0)"),
    ("EndDisabled", "", "", "igEndDisabled()"),
    ("IsItemHovered", "bool", "flags:int", "igIsItemHovered(flags)"),
    ("IsItemActive", "bool", "", "igIsItemActive()"),
    ("IsItemClicked", "bool", "button:int", "igIsItemClicked(button)"),
    ("IsWindowFocused", "bool", "flags:int", "igIsWindowFocused(flags)"),
    ("IsWindowHovered", "bool", "flags:int", "igIsWindowHovered(flags)"),
    ("WindowWidth", "float32", "", "igGetWindowWidth()"),
    ("WindowHeight", "float32", "", "igGetWindowHeight()"),
    ("CursorPosX", "float32", "", "igGetCursorPosX()"),
    ("CursorPosY", "float32", "", "igGetCursorPosY()"),
    ("SetCursorPosX", "", "x:float32", "igSetCursorPosX(x)"),
    ("SetCursorPosY", "", "y:float32", "igSetCursorPosY(y)"),
    ("SetNextItemWidth", "", "width:float32", "igSetNextItemWidth(width)"),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    root = parser.parse_args().root
    # 主仓库优先写规范源码，再同步构建镜像；独立构建仓直接写自身 sdk。
    canonical = root.parent / "sdk/ios/imgui"
    sdk = canonical if (root.parent / "go.mod").is_file() and canonical.is_dir() else root / "sdk/ios/imgui"
    vendor = root / "host/ios/third_party/cimgui"
    header = (vendor / "cimgui.h").read_text(encoding="utf-8")
    c_types = {"string": "const char *", "int": "int", "bool": "int", "float32": "float"}
    c_returns = {"": "void", "bool": "int", "float32": "float"}
    go = ['// Code generated by tools/imgui_bindings.py. DO NOT EDIT.\n// 控件只允许在 Run 绘制回调中调用。\n//go:build ios && cgo\n\npackage imgui\n/*\n#include <stdlib.h>\n#include "ag_widgets_gen.h"\n*/\nimport "C"\nimport "unsafe"\n']
    stub = ['// Code generated by tools/imgui_bindings.py. DO NOT EDIT.\n//go:build !ios || !cgo\n\npackage imgui\nimport "autogov1/v2/sdk/ios/types"\n']
    h = ['// Code generated by tools/imgui_bindings.py. DO NOT EDIT.\n#pragma once\n#ifdef __cplusplus\nextern "C" {\n#endif\n']
    cpp = ['// Code generated by tools/imgui_bindings.py. DO NOT EDIT.\n#include "imgui.h"\n#include "imgui_internal.h"\n#include "cimgui.h"\n#include "ag_widgets_gen.h"\nextern "C" {\n']
    for name, ret, params, call in SPECS:
        callee = call.split("(")[0]
        if callee + "(" not in header:
            raise ValueError("cimgui 头文件没有入口：" + callee)
        args = [part.split(":") for part in params.split(",") if part]
        signature = ",".join(n+" "+t for n,t in args)
        declaration = c_returns[ret] + " agIm" + name + "(" + (",".join(c_types[t]+" "+n for n,t in args) or "void") + ")"
        h.append(declaration + ";\n")
        cpp.append(declaration + " { " + (("return " + call + (" ? 1 : 0" if ret == "bool" else "")) if ret else call) + "; }\n")
        go.append("func "+name+"("+signature+") "+ret+" { requireFrame()\n")
        converted = []
        for n,t in args:
            if t == "string":
                go.append(f"c{n}:=C.CString({n}); defer C.free(unsafe.Pointer(c{n}))\n")
                converted.append("c"+n)
            elif t == "bool":
                go.append(f"var c{n} C.int; if {n} {{ c{n}=1 }}\n")
                converted.append("c"+n)
            else:
                converted.append(("C.float" if t == "float32" else "C.int")+"("+n+")")
        invoke = "C.agIm"+name+"("+",".join(converted)+")"
        go.append(("return "+invoke+"!=0" if ret == "bool" else "return float32("+invoke+")" if ret else invoke)+"\n}\n")
        stub.append("func "+name+"("+signature+") "+ret+" { panic(types.ErrUnsupported) }\n")
    h.append('#ifdef __cplusplus\n}\n#endif\n');cpp.append('}\n')
    for path, parts in [(sdk/"widgets_gen.go",go),(sdk/"widgets_stub_gen.go",stub),(sdk/"ag_widgets_gen.h",h),(vendor/"ag_widgets_gen.cpp",cpp)]:
        path.write_text("".join(parts),encoding="utf-8")
    formatter = shutil.which("gofmt")
    if not formatter:
        raise SystemExit("需要 Go 工具链中的 gofmt；生成器只格式化源码，不运行编译或测试")
    subprocess.run([formatter,"-w",str(sdk/"widgets_gen.go"),str(sdk/"widgets_stub_gen.go")],check=True)
    mirror = root / "sdk/ios/imgui"
    if mirror.resolve() != sdk.resolve():
        for name in ["widgets_gen.go","widgets_stub_gen.go","ag_widgets_gen.h"]:
            shutil.copyfile(sdk/name,mirror/name)


if __name__ == "__main__":
    main()
