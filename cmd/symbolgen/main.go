// symbolgen 扫 SDK 包，生成 yaegi 的符号表。
//
// 【为什么需要】
// 参考实现的脚本能直接写：
//	import "github.com/…/AutoGo/ppocr"
//	p := ppocr.New("v5")
// 是因为整个 SDK 作为二进制符号注册进了解释器。
// 我们的脚本要能同样写 motion.Click(500, 800, 0)，就必须把 SDK 的
// 导出函数登记成 interp.Exports —— 手写 222 个既易漏又会跟实现漂移，
// 所以用 go/ast 扫包自动生成。
//
// 【只导出"能被反射装进 interpreter"的函数】
// yaegi 的符号表只接受 Go 基础类型与已注册的类型；
// 带 context.Context、自定义 struct、泛型、接口的函数跳过，
// 那些能力脚本用 api.Call(op, args) 走原生通道即可（两条路并存）。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// eligible 判断一个类型表达式能不能安全注册进解释器符号表。
//
// 规则刻意保守：宁可少导出一个函数，也不要在运行期炸在脚本里。
func eligible(expr ast.Expr) bool {
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "int", "int64", "int32", "float64", "float32", "string", "bool", "byte", "rune", "error", "any":
			return true
		}
		return false
	case *ast.ArrayType:
		// []byte / [N]byte 之类；元素必须是基础类型
		return eligible(t.Elt)
	case *ast.StarExpr:
		return false // 指针交给 api.Call
	case *ast.SelectorExpr:
		return false // 外部包类型（time.Duration、context.Context…）不导出
	case *ast.MapType, *ast.ChanType, *ast.FuncType, *ast.InterfaceType, *ast.StructType:
		return false
	}
	return false
}

// funcEligible 判断函数签名（含多返回值）是否全部可选。
func funcEligible(fn *ast.FuncDecl) bool {
	if fn.Recv != nil {
		return false // 只导出包级函数；方法留给 api.Call
	}
	if fn.Type.Params != nil {
		for _, field := range fn.Type.Params.List {
			if !eligible(field.Type) {
				return false
			}
		}
	}
	if fn.Type.Results != nil {
		for _, field := range fn.Type.Results.List {
			if !eligible(field.Type) {
				return false
			}
		}
	}
	return true
}

func main() {
	var (
		root   = flag.String("root", ".", "模块根目录")
		out    = flag.String("out", "sdk/ios/script/api/symbols_gen.go", "输出文件")
		pkgArg = flag.String("pkgs", "motion,device,app,files,utils,system,ime,https,storages", "要扫描的包名（逗号分隔）")
	)
	flag.Parse()

	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/symbolgen. DO NOT EDIT.\n\n")
	buf.WriteString("// 脚本可见的 SDK 包符号表。\n")
	buf.WriteString("//\n")
	buf.WriteString("// 生成规则：只登记「签名里全是可以反射构造的基础类型」的包级函数；\n")
	buf.WriteString("// 带 context / 自定义结构体 / 接口的函数不在这里 —— 那类能力脚本用 api.Call(op, args)。\n")
	buf.WriteString("package api\n\n")
	buf.WriteString("import (\n\t\"reflect\"\n\n\t\"github.com/traefik/yaegi/interp\"\n")
	for _, pkg := range strings.Split(*pkgArg, ",") {
		pkg = strings.TrimSpace(pkg)
		if pkg == "" {
			continue
		}
		fmt.Fprintf(&buf, "\n\tagov%s \"autogov1/v2/sdk/ios/%s\"", pkg, pkg)
	}
	buf.WriteString("\n)\n\n")
	buf.WriteString("// SDKPackages 供 Runner 调 interp.Use(SDKPackages)。\n")
	buf.WriteString("//\n")
	buf.WriteString("// 键名格式是 yaegi 的约定：\"导入路径/包名\"（标准库那份也是 \"fmt/fmt\"）。\n")
	buf.WriteString("// 写成只有导入路径时，脚本 import 会报 undefined: <pkg> —— 这里踩过一次。\n")
	buf.WriteString("var SDKPackages = interp.Exports{\n")

	total := 0
	for _, pkg := range strings.Split(*pkgArg, ",") {
		pkg = strings.TrimSpace(pkg)
		if pkg == "" {
			continue
		}
		dir := filepath.Join(*root, "sdk", "ios", pkg)
		names, err := scanPackage(dir)
		if err != nil {
			fmt.Fprintf(os.Stderr, "跳过 %s: %v\n", pkg, err)
			continue
		}
		if len(names) == 0 {
			continue
		}
		fmt.Fprintf(&buf, "\t%q: {\n", "autogov1/v2/sdk/ios/"+pkg+"/"+pkg)
		for _, name := range names {
			fmt.Fprintf(&buf, "\t\t%q: reflect.ValueOf(agov%s.%s),\n", name, pkg, name)
			total++
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, buf.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("生成 %s：%d 个符号\n", *out, total)
}

// scanPackage 解析目录下所有 .go（跳过测试与内部实现细节），返回可导出的函数名。
func scanPackage(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	fset := token.NewFileSet()
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(dir, entry.Name()), nil, 0)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || !fn.Name.IsExported() || !funcEligible(fn) {
				continue
			}
			names = append(names, fn.Name.Name)
		}
	}
	sort.Strings(names)
	// 去重（同名函数不该出现，但 cgo 文件可能重复声明）
	dedup := names[:0]
	var last string
	for _, name := range names {
		if name != last {
			dedup = append(dedup, name)
			last = name
		}
	}
	return dedup, nil
}

// 保持 printer 导入用于调试（需要时可打印签名）。
