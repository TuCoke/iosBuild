// symbolgen 生成公开函数、类型、常量与变量绑定；方法随类型导出。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type symbol struct{ Name, Kind string }

func scanPackage(dir string) ([]symbol, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	symbols := map[string]string{}
	add := func(n, k string) error {
		if !ast.IsExported(n) {
			return nil
		}
		if previous, ok := symbols[n]; ok && previous != k {
			return fmt.Errorf("符号类别冲突: %s", n)
		}
		symbols[n] = k
		return nil
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		file, e := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, entry.Name()), nil, 0)
		if e != nil {
			return nil, e
		}
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil && (d.Type.TypeParams == nil || len(d.Type.TypeParams.List) == 0) {
					if e = add(d.Name.Name, "func"); e != nil {
						return nil, e
					}
				}
			case *ast.GenDecl:
				for _, sp := range d.Specs {
					switch v := sp.(type) {
					case *ast.TypeSpec:
						if v.TypeParams == nil || len(v.TypeParams.List) == 0 {
							if e = add(v.Name.Name, "type"); e != nil {
								return nil, e
							}
						}
					case *ast.ValueSpec:
						k := "const"
						if d.Tok == token.VAR {
							k = "var"
						}
						for _, n := range v.Names {
							if e = add(n.Name, k); e != nil {
								return nil, e
							}
						}
					}
				}
			}
		}
	}
	result := make([]symbol, 0, len(symbols))
	for n, k := range symbols {
		result = append(result, symbol{n, k})
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Name < result[j].Name })
	return result, nil
}
func main() {
	root := flag.String("root", ".", "模块根目录")
	out := flag.String("out", "sdk/ios/script/api/symbols_gen.go", "输出文件")
	packages := flag.String("pkgs", "", "空值时扫描全部公开能力包，排除解释器自身")
	flag.Parse()
	var names []string
	if *packages != "" {
		for _, n := range strings.Split(*packages, ",") {
			if n = strings.TrimSpace(n); n != "" {
				names = append(names, n)
			}
		}
	} else {
		entries, e := os.ReadDir(filepath.Join(*root, "sdk", "ios"))
		if e != nil {
			panic(e)
		}
		for _, v := range entries {
			if v.IsDir() && v.Name() != "script" && v.Name() != "internal" && v.Name() != "examples" && v.Name() != "selftest" {
				names = append(names, v.Name())
			}
		}
	}
	sort.Strings(names)
	sets := map[string][]symbol{}
	total := 0
	for _, n := range names {
		s, e := scanPackage(filepath.Join(*root, "sdk", "ios", n))
		if e != nil {
			panic(e)
		}
		if len(s) > 0 {
			sets[n] = s
			total += len(s)
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/symbolgen. DO NOT EDIT.\n// 指针类型与构造函数不再被静默遗漏。\npackage api\nimport(\n\"reflect\"\n\"github.com/traefik/yaegi/interp\"\n")
	for _, n := range names {
		if len(sets[n]) > 0 {
			fmt.Fprintf(&b, "sdk%s %q\n", n, "autogov1/v2/sdk/ios/"+n)
		}
	}
	b.WriteString(")\nvar SDKPackages=interp.Exports{\n")
	for _, n := range names {
		if len(sets[n]) == 0 {
			continue
		}
		fmt.Fprintf(&b, "%q:{\n", "autogov1/v2/sdk/ios/"+n+"/"+n)
		for _, s := range sets[n] {
			switch s.Kind {
			case "type":
				fmt.Fprintf(&b, "%q:reflect.ValueOf((*sdk%s.%s)(nil)),\n", s.Name, n, s.Name)
			case "var":
				fmt.Fprintf(&b, "%q:reflect.ValueOf(&sdk%s.%s).Elem(),\n", s.Name, n, s.Name)
			default:
				fmt.Fprintf(&b, "%q:reflect.ValueOf(sdk%s.%s),\n", s.Name, n, s.Name)
			}
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	source, e := format.Source(b.Bytes())
	if e != nil {
		panic(e)
	}
	if e = os.MkdirAll(filepath.Dir(*out), 0755); e != nil {
		panic(e)
	}
	if e = os.WriteFile(*out, source, 0644); e != nil {
		panic(e)
	}
	fmt.Printf("生成 %s: %d 个包 / %d 个符号\n", *out, len(sets), total)
}
